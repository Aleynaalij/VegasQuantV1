import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
await db.exec(`
create schema auth; create schema private; create role anon; create role authenticated;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
create table auth.users(id uuid primary key,email_confirmed_at timestamptz,banned_until timestamptz);
create table public.community_profiles(user_id uuid,username text,avatar text,visible boolean);
alter table public.community_profiles enable row level security;
create policy own_profile on public.community_profiles to authenticated using(user_id=auth.uid());
create table public.member_blocks(user_id uuid,target_user_id uuid);
create table public.community_posts(id uuid primary key,user_id uuid,sport text,created_at timestamptz);
alter table public.community_posts enable row level security;
create function private.community_member_allowed(target uuid) returns boolean language sql security definer set search_path='' as $$select auth.uid() is not null and not exists(select 1 from public.member_blocks where (user_id=auth.uid() and target_user_id=target) or (target_user_id=auth.uid() and user_id=target))$$;
create policy read_posts on public.community_posts to authenticated using(private.community_member_allowed(user_id));
create table public.community_reactions(post_id uuid,user_id uuid);
create table public.community_post_comments(post_id uuid);
create table public.member_follows(user_id uuid,target_user_id uuid);
grant usage on schema public,private,auth to authenticated;
grant select on public.community_posts,public.community_reactions,public.community_post_comments,public.member_follows to authenticated;
insert into auth.users select ('00000000-0000-4000-8000-'||lpad(i::text,12,'0'))::uuid,now(),null from generate_series(1,5)i;
insert into public.community_profiles select id,'Member'||row_number() over(order by id),'photo',true from auth.users;
update public.community_profiles set visible=false where username='Member3';
update auth.users set banned_until=now()+interval '1 day' where id='00000000-0000-4000-8000-000000000004';
insert into public.community_posts select ('10000000-0000-4000-8000-'||lpad(i::text,12,'0'))::uuid,('00000000-0000-4000-8000-'||lpad(i::text,12,'0'))::uuid,'nfl',now()-interval '1 hour' from generate_series(1,5)i;
insert into public.community_posts values('20000000-0000-4000-8000-000000000002','00000000-0000-4000-8000-000000000002','nba',now());
insert into public.community_reactions values('20000000-0000-4000-8000-000000000002','00000000-0000-4000-8000-000000000001');
`);
await db.exec(fs.readFileSync('supabase/migrations/20261016151703_community_activity_bar.sql','utf8'));
await db.exec(`set role authenticated; select set_config('test.uid','00000000-0000-4000-8000-000000000001',false);`);
const activity = async () => (await db.query('select public.community_activity() as data')).rows[0].data;
let rows=await activity();
assert.equal(rows.length,3); // self, visible Member2 and Member5; private and banned excluded.
assert.equal(rows[0].username,'Member2');
assert.equal(rows[0].sport,'nba');
assert.equal(rows.filter(x=>x.username==='Member2').length,1);
assert.deepEqual(Object.keys(rows[0]).sort(),['avatar','created_at','post_id','sport','username']);
let post=(await db.query("select public.community_post('20000000-0000-4000-8000-000000000002') as data")).rows[0].data;
assert.equal(post.reactions,1); assert.equal(post.reacted,true);
await db.exec(`reset role; insert into public.member_blocks values('00000000-0000-4000-8000-000000000002','00000000-0000-4000-8000-000000000001'); set role authenticated;`);
assert.equal((await activity()).some(x=>x.username==='Member2'),false);
assert.equal((await db.query("select public.community_post('20000000-0000-4000-8000-000000000002') as data")).rows[0].data,null);
await db.exec("select set_config('test.uid','',false)");
assert.deepEqual(await activity(),[]);
await db.exec('reset role; set role anon');
await assert.rejects(db.query('select public.community_activity()'));
await assert.rejects(db.query("select public.community_post('20000000-0000-4000-8000-000000000002')"));
await db.close();
console.log('Community activity: latest author, cross-sport links, privacy, bans, bidirectional blocks, exact post counts, anonymous denial passed');
